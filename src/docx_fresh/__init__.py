"""Give a python-docx document fresh metadata instead of the default template's.

``Document()`` without a template copies the document properties of python-docx's
bundled ``default.docx``: author "python-docx", created and modified 2013-12-23,
application "Microsoft Macintosh Word", one page, and the template's thumbnail.
:func:`fresh` replaces those values and leaves anything else alone.
"""

from __future__ import annotations

import datetime as dt
from typing import TYPE_CHECKING

from lxml import etree

if TYPE_CHECKING:
    from docx.document import Document

__all__ = ["fresh", "TEMPLATE_AUTHOR", "TEMPLATE_COMMENTS", "TEMPLATE_TIME"]
__version__ = "0.1.0"

TEMPLATE_AUTHOR = "python-docx"
TEMPLATE_COMMENTS = "generated by python-docx"
TEMPLATE_TIME = dt.datetime(2013, 12, 23, 23, 15, tzinfo=dt.timezone.utc)

_RT_THUMBNAIL = "http://schemas.openxmlformats.org/package/2006/relationships/metadata/thumbnail"
_RT_EXTENDED = (
    "http://schemas.openxmlformats.org/officeDocument/2006/relationships/extended-properties"
)
_EP = "{http://schemas.openxmlformats.org/officeDocument/2006/extended-properties}"

# Values in app.xml that only the application that last saved the file can know.
# They are optional, and Word rewrites them on its next save.
_STALE_APP_ELEMENTS = (
    "Application",
    "AppVersion",
    "TotalTime",
    "Pages",
    "Words",
    "Characters",
    "CharactersWithSpaces",
    "Lines",
    "Paragraphs",
)


def fresh(
    document: Document,
    *,
    author: str = "",
    now: dt.datetime | None = None,
) -> Document:
    """Replace the default template's metadata in ``document`` and return it.

    Only values still equal to the template's are changed, so a document made from
    your own template keeps its author, dates and thumbnail.

    - author and last modified by "python-docx" become ``author`` (empty by default)
    - the comment "generated by python-docx" is cleared
    - created and modified 2013-12-23 become ``now`` (the current UTC time by default)
    - app.xml loses the application name, version and page, word and line counts
    - the template's thumbnail is dropped

    The document's revision number is kept.
    """
    if now is None:
        now = dt.datetime.now(dt.timezone.utc)
    if now.tzinfo is None:
        raise ValueError("now must be timezone-aware, for example datetime.now(timezone.utc)")
    now = now.astimezone(dt.timezone.utc).replace(microsecond=0)

    props = document.core_properties
    from_template = props.author == TEMPLATE_AUTHOR or props.created == TEMPLATE_TIME
    if props.author == TEMPLATE_AUTHOR:
        props.author = author
    if props.last_modified_by == TEMPLATE_AUTHOR or (from_template and not props.last_modified_by):
        props.last_modified_by = author
    if props.comments == TEMPLATE_COMMENTS:
        props.comments = ""
    if props.created == TEMPLATE_TIME:
        props.created = now
    if props.modified == TEMPLATE_TIME:
        props.modified = now

    if from_template:
        package = document.part.package
        _drop_rels(package, _RT_THUMBNAIL)
        _clean_app_xml(package)
    return document


def _drop_rels(package, reltype: str) -> None:
    for r_id in [r_id for r_id, rel in package.rels.items() if rel.reltype == reltype]:
        del package.rels[r_id]


def _clean_app_xml(package) -> None:
    for rel in package.rels.values():
        if rel.reltype != _RT_EXTENDED or rel.is_external:
            continue
        part = rel.target_part
        root = etree.fromstring(part.blob)
        for name in _STALE_APP_ELEMENTS:
            for el in root.findall(_EP + name):
                root.remove(el)
        # A generic python-docx Part serializes whatever is in ``_blob``.
        part._blob = etree.tostring(root, xml_declaration=True, encoding="UTF-8", standalone=True)
